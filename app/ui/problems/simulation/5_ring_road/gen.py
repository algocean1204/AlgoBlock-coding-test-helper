def random_road(rng, n, cars):
    """n칸 도로에 자동차를 cars/10의 확률로 놓는다."""
    return ''.join('>' if rng.chance(cars, 10) else '.' for _ in range(n))


def small(rng):
    cases = [
        [">.", 1],                                    # 가장 짧은 도로
        [".>", 5],                                    # 첫 1초에 바로 결승선
        [">>", 10],                                   # 꽉 차서 움직이지 않는다
        ["..", 7],                                    # 자동차가 없다
        [".....>", 1],
        [">>>.", 100],
        ["....>>>>", 97],                             # 몰린 자동차가 결승선 바로 앞
        [">>>>>.....", 1000],
        [">>>>>>>.>", 300],                           # 거의 꽉 찬 도로
        [">" * 30, 3000],
        ["." * 29 + ">", 3000],
        [">" * 15 + "." * 15, 2999],                  # 절반이 몰려 있다
        [">" * 20 + "." * 10, 2500],                  # 막힘이 풀리는 데 오래 걸린다
        [".>>.>>>..>.>>>>.....>>.", 777],
        # 처음 몇 초의 모습이 다시 나오지 않고, 그동안 결승선을 지나간 횟수가 주기 안의 같은 길이 구간과 다르다
        [">" * 13 + "." * 10, 1386],
        [">" * 9 + "." * 11, 860],
        [".>>.>.>>...>", 632],
        [">..>>>>>>.>.....>.", 1694],
    ]
    for _ in range(2):
        cases.append([random_road(rng, rng.randint(5, 30), rng.randint(2, 8)), rng.randint(1, 3000)])
    return cases


def medium(rng):
    """t가 아주 큰 정확성 케이스: int 넘침과 꼬리·남은 부분 계산 실수를 '틀림'으로 잡는다."""
    return [
        [">.", 1_000_000_000_000],                  # 2초마다 한 번: 500,000,000,000
        [">>>>...", 1_000_000_000_000],             # 4초 꼬리 뒤 7초 주기: 5, 7, 9초째에 지나고 7초마다 되풀이 → 428,571,428,570
        [">>>>>.....", 999_999_999_999],            # 4초 꼬리 뒤 2초 주기: 6초째부터 2초마다 → 499,999,999,997
        [">" * 13 + "." * 10, 1_000_000_000_000],
        [">>.>.>>>...>>>>.>...", 987_654_321_098],
        [">>", 1_000_000_000_000],                  # 꽉 차서 0
    ]


def valid(road, t):
    return 2 <= len(road) <= 1000 and set(road) <= set(">.") and 1 <= t <= 1_000_000_000_000


