def large(rng, index):
    if index == 0:  # 듬성듬성한 도로: 곧 모두 매초 달린다
        return [random_road(rng, 1000, 3), 1_000_000_000_000]
    if index == 1:  # 앞쪽 600칸에 몰려 있다: 막힘이 풀리는 데 오래 걸린다
        return ['>' * 600 + '.' * 400, rng.randint(900_000_000_000, 1_000_000_000_000)]
    return [random_road(rng, 1000, 5), rng.randint(900_000_000_000, 1_000_000_000_000)]  # 절반쯤 찬 도로
